// Bundles the existing ES-module engine (src/**) into a single classic
// (non-module) script for web-build/engine.bundle.js, so the browser build
// can run over file:// without hitting Chrome's CORS block on cross-file
// `import`. This ONLY strips `import`/`export` syntax -- no game logic is
// added, removed, or altered. Re-run after any engine change under src/.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Dependency order matters: a file must come after everything it references.
const FILES = [
  'src/utils/shuffle.js',
  'src/cards/Card.js',
  'src/cards/Deck.js',
  'src/cards/starterCards.js',
  'src/game/Vessel.js',
  'src/game/Enemy.js',
  'src/game/Combat.js',
  'src/game/BossCombat.js',
  'src/game/abilities.js',
  'src/game/enemyAbilities.js',
  'src/game/enemies.js',
  'src/game/bossRoster.js',
  'src/run/RunMap.js',
  'src/run/Run.js',
  'src/run/backgrounds.js',
  'src/narrative/NarrativeEngine.js',
  'src/narrative/shards.js',
];

function stripModuleSyntax(source) {
  return source
    // Multi-line `import { ... } from '...';`
    .replace(/^import\s*\{[\s\S]*?\}\s*from\s*['"][^'"]*['"];?\s*$/gm, '')
    // Single-line `import X from '...';` / `import { X } from '...';`
    .replace(/^import\s+.*from\s*['"][^'"]*['"];?\s*$/gm, '')
    // `export class` / `export const` / `export function` -> drop the `export ` prefix
    .replace(/^export\s+(class|const|function|let)\s/gm, '$1 ');
}

const banner = (relPath) => `\n// ---- ${relPath} (bundled, import/export stripped) ----\n`;

const bundled = FILES.map((relPath) => {
  const full = path.join(ROOT, relPath);
  const source = fs.readFileSync(full, 'utf8');
  return banner(relPath) + stripModuleSyntax(source).trim() + '\n';
}).join('\n');

const header =
  '// AUTO-GENERATED by scripts/bundle-web-engine.mjs -- do not hand-edit.\n' +
  '// Source of truth is src/**; re-run the bundler after engine changes.\n';

const outPath = path.join(ROOT, 'web-build/engine.bundle.js');
fs.writeFileSync(outPath, header + bundled);
console.log(`Wrote ${outPath} (${bundled.length} bytes)`);
